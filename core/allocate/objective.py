"""Целевая функция оптимизации.

ЗАФИКСИРОВАНА (AGENT.md §7): `α·makespan + (1−α)·суммарный налёт`.
Изменение весов, добавление слагаемых и смена нормировки — только по явной
задаче от команды. Отдельный модуль ровно для того, чтобы формула не
расползлась по оптимизатору копиями.
"""

from __future__ import annotations


def objective_value(makespan_s: float, total_flight_time_s: float, alpha: float) -> float:
    """Значение целевой функции плана.

    Оба слагаемых — в секундах, поэтому нормировка не нужна и сумма
    осмысленна: при α=1 минимизируется время выполнения работ, при α=0 —
    суммарный налёт всех бортов.

    Args:
        makespan_s: время выполнения всех работ, секунды.
        total_flight_time_s: суммарный налёт всех бортов, секунды.
        alpha: вес makespan, доля 0..1.

    Returns:
        Значение целевой функции, секунды. Меньше — лучше.
    """
    if not 0.0 <= alpha <= 1.0:
        raise ValueError(f"alpha должна лежать в [0, 1], получено {alpha}")
    return alpha * makespan_s + (1.0 - alpha) * total_flight_time_s


__all__ = ["objective_value"]
