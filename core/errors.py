"""Типизированные ошибки ядра.

Исключения — для ОШИБОК ВХОДА: некорректная геометрия, недопустимые значения,
неизвестный борт. Они отвергаются на приёме (заказчик, №19). Невыполнимость
задания — не исключение, а результат: `Mission.status = infeasible` с
причинами и рекомендациями (инвариант 10).

Всё, что ядро бросает осознанно, наследуется от `CoreError`, и API (E9)
отображает это в осмысленный HTTP-код, а не в 500.
"""

from __future__ import annotations


class CoreError(Exception):
    """Базовая ошибка ядра. Всё осознанное наследуется отсюда."""


class ScenarioError(CoreError):
    """Сценарий синтаксически разобран, но содержательно непригоден.

    Например: область съёмки вырождена, площадка лежит внутри запретной зоны,
    во флоте указан борт, которого нет в каталоге.
    """


class CatalogError(CoreError):
    """Проблема каталога техники `data/vehicles.yaml`.

    Отдельный тип, потому что инвариант 6 запрещает «починить» отсутствующую
    ТТХ правдоподобным числом: пробел должен быть виден.
    """


class GeometryError(CoreError):
    """Геометрия не поддаётся обработке: самопересечение, пустая маска, NaN."""


class InfeasibleError(CoreError):
    """Физически невыполнимое действие на уровне одной функции.

    Например, курс, который борт не выдержит при данном ветре. На уровне
    конвейера невыполнимость — не исключение, а статус плана.
    """


class StageNotImplementedError(CoreError):
    """Стадия конвейера ещё не реализована и заглушки для неё нет.

    Бросается вместо возврата пустого результата: молчаливый пустой план
    выглядит на демонстрации как настоящий.
    """


__all__ = [
    "CatalogError",
    "CoreError",
    "GeometryError",
    "InfeasibleError",
    "ScenarioError",
    "StageNotImplementedError",
]
