"""Реестр физических констант и допущений — ЕДИНСТВЕННОЕ место в проекте.

ИНВАРИАНТ 5 (PROJECT_BRIEF.md §5): магические числа в коде расчётов запрещены.
Любое число, не являющееся математической константой самого выражения, живёт
здесь и снабжено источником.

Реестр машиночитаемый. `python -m core.cli assumptions` печатает его целиком,
и из этого же вывода растёт раздел «известные ограничения» документации,
который требует ТЗ (E13). Поэтому каждая запись обязана иметь `kind`:

* ``MEASURED``  — физическая константа или ТТХ из официального документа.
* ``TEAM``      — ДОПУЩЕНИЕ КОМАНДЫ. Источника не существует, число выбрано нами.
                  Каждая такая запись — строка в «известных ограничениях».
* ``DERIVED``   — выведено из `MEASURED` по явной формуле, указанной в `rationale`.

Инвариант 6 остаётся в силе: ТТХ БВС здесь НЕ дублируются, они в
`data/vehicles.yaml`. Здесь — только правила, которыми заполняются пробелы
этого каталога.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from enum import Enum
from typing import TypeVar


class Kind(str, Enum):
    """Происхождение числа."""

    MEASURED = "measured"
    TEAM = "team_assumption"
    DERIVED = "derived"


@dataclass(frozen=True)
class Assumption:
    """Одна запись реестра."""

    name: str
    value: object
    unit: str
    kind: Kind
    source: str
    rationale: str = ""

    def is_team_assumption(self) -> bool:
        """True — число выбрано командой, а не взято из источника."""
        return self.kind is Kind.TEAM


_REGISTRY: dict[str, Assumption] = {}

T = TypeVar("T")


def _register(
    name: str,
    value: T,
    unit: str,
    kind: Kind,
    source: str,
    rationale: str = "",
) -> T:
    """Зарегистрировать допущение и вернуть его значение.

    Значение возвращается, чтобы константа объявлялась одной строкой и
    использовалась в коде как обычное число, но при этом не могла появиться
    в проекте в обход реестра.
    """
    if name in _REGISTRY:
        raise ValueError(f"Допущение {name!r} уже зарегистрировано")
    _REGISTRY[name] = Assumption(
        name=name, value=value, unit=unit, kind=kind, source=source, rationale=rationale
    )
    return value


def all_assumptions() -> list[Assumption]:
    """Весь реестр в порядке объявления."""
    return list(_REGISTRY.values())


def team_assumptions() -> list[Assumption]:
    """Только допущения команды — основа раздела «известные ограничения» (E13)."""
    return [item for item in _REGISTRY.values() if item.is_team_assumption()]


def get(name: str) -> Assumption:
    """Запись реестра по имени."""
    return _REGISTRY[name]


