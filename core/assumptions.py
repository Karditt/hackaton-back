def fixed_wing_turn_radius_m(cruise_speed_mps: float) -> float:
    """Минимальный радиус разворота борта самолётного типа.

    Координированный разворот с постоянным креном: r = V² / (g · tan φ).

    Args:
        cruise_speed_mps: воздушная скорость в развороте, м/с.

    Returns:
        Радиус разворота, метры.
    """
    if cruise_speed_mps <= 0:
        raise ValueError("Скорость в развороте должна быть положительной")
    return cruise_speed_mps**2 / (G_MPS2 * math.tan(math.radians(FIXED_WING_BANK_ANGLE_DEG)))


